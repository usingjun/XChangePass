#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "$0")/../.." && pwd)"

cd "$ROOT_DIR"

RUN_TRANSACTION_STATISTICS_BENCHMARK=true \
TRANSACTION_STATISTICS_BENCHMARK_ROWS="${TRANSACTION_STATISTICS_BENCHMARK_ROWS:-100000}" \
TRANSACTION_STATISTICS_BENCHMARK_USERS="${TRANSACTION_STATISTICS_BENCHMARK_USERS:-1000}" \
TRANSACTION_STATISTICS_BENCHMARK_MONTHS="${TRANSACTION_STATISTICS_BENCHMARK_MONTHS:-12}" \
TRANSACTION_STATISTICS_BENCHMARK_SEED="${TRANSACTION_STATISTICS_BENCHMARK_SEED:-20260704}" \
TRANSACTION_STATISTICS_BENCHMARK_WARMUP="${TRANSACTION_STATISTICS_BENCHMARK_WARMUP:-5}" \
TRANSACTION_STATISTICS_BENCHMARK_ITERATIONS="${TRANSACTION_STATISTICS_BENCHMARK_ITERATIONS:-50}" \
./gradlew test \
  --tests 'bumblebee.xchangepass.domain.transaction.statistics.TransactionStatisticsBenchmarkRunnerTest'

echo "Result: $ROOT_DIR/build/perf/transaction-statistics-benchmark-results.csv"
